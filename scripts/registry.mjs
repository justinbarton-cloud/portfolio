#!/usr/bin/env node
// Writes content/registry.generated.ts: one import per case in
// content/work/, so adding a case is adding a file. Runs before dev, build
// and check, and isn't committed.
import { existsSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const content = new URL('../content/', import.meta.url).pathname
const dir = join(content, 'work')
const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.ts')).sort() : []
const ident = (f) => 'case_' + f.slice(0, -3).replace(/[^A-Za-z0-9]/g, '_')
writeFileSync(
  join(content, 'registry.generated.ts'),
  `// GENERATED by scripts/registry.mjs. Do not edit. Add a file to content/work/ instead.
${files.map((f) => `import ${ident(f)} from './work/${f.slice(0, -3)}'`).join('\n')}

export const work = [${files.map((f) => `{ file: '${f.slice(0, -3)}', work: ${ident(f)} }`).join(', ')}]
`,
)
console.log(`registry: ${files.length} cases`)
