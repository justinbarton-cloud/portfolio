#!/usr/bin/env node
// Writes content/registry.generated.ts: one import per case in
// content/work/, so adding a case is adding a file. Runs before dev, build
// and check, and isn't committed. Both lists are typed, so an empty one
// (the public build has no reels) still type checks. When npm run preview has copied the
// private drafts into content/drafts/, they're listed too, for local review.
import { existsSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const content = new URL('../content/', import.meta.url).pathname
const list = (sub) => {
  const dir = join(content, sub)
  return existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.ts')).sort().map((f) => ({ sub, f })) : []
}
const files = [...list('work'), ...list('drafts')]
const reels = [...list('reels'), ...list('drafts/reels')]
const ident = ({ sub, f }) => `${sub.replace('/', '_')}_` + f.slice(0, -3).replace(/[^A-Za-z0-9]/g, '_')
writeFileSync(
  join(content, 'registry.generated.ts'),
  `// GENERATED by scripts/registry.mjs. Do not edit. Add a file to content/work/ or content/reels/ instead.
import type { Case, Reel } from './types'
${[...files, ...reels].map((x) => `import ${ident(x)} from './${x.sub}/${x.f.slice(0, -3)}'`).join('\n')}

export const work: { file: string; work: Case }[] = [${files.map((x) => `{ file: '${x.f.slice(0, -3)}', work: ${ident(x)} }`).join(', ')}]
export const reels: { file: string; reel: Reel }[] = [${reels.map((x) => `{ file: '${x.f.slice(0, -3)}', reel: ${ident(x)} }`).join(', ')}]
`,
)
const drafts = files.filter((x) => x.sub === 'drafts').length
console.log(`registry: ${files.length - drafts} cases${drafts ? `, plus ${drafts} drafts for preview` : ''}, ${reels.length} reels`)
